"""Third-party component and license record, produced by tooling (spec 06
REQ-8.4), evaluated against a declared policy (spec 06 REQ-8.4a; spec 01
REQ-10.5). Never hand-maintained: the record is regenerated from the
dependency manifests and lockfiles in the tree.
"""
import json
import pathlib
import re

RECORD = ".engine/records/licenses.tsv"
POLICY = ".engine/license-policy.json"
COLUMNS = ["component", "version", "license", "source"]


def _node_lock(root):
    p = root / "package-lock.json"
    if not p.is_file():
        return []
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except ValueError:
        return [("package-lock.json", "?", "UNPARSEABLE", "package-lock.json")]
    out = []
    for path, meta in (data.get("packages") or {}).items():
        if not path or not isinstance(meta, dict):
            continue
        name = path.split("node_modules/")[-1]
        lic = meta.get("license")
        if lic is None:
            pj = root / path / "package.json"
            if pj.is_file():
                try:
                    lic = json.loads(pj.read_text(encoding="utf-8")).get("license")
                except ValueError:
                    lic = None
        if isinstance(lic, dict):
            lic = lic.get("type")
        out.append((name, str(meta.get("version", "?")), str(lic or "UNKNOWN"), "package-lock.json"))
    return out


def _python_requirements(root):
    out = []
    for req in sorted(root.glob("requirements*.txt")):
        for line in req.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.split("#")[0].strip()
            if not line or line.startswith("-"):
                continue
            m = re.match(r"([A-Za-z0-9_.-]+)\s*(?:[=~!<>]+\s*([^\s;]+))?", line)
            if not m:
                continue
            name, version = m.group(1), m.group(2) or "?"
            lic = "UNKNOWN"
            try:
                from importlib import metadata
                md = metadata.metadata(name)
                lic = md.get("License-Expression") or md.get("License") or "UNKNOWN"
                if lic == "UNKNOWN":
                    for c in md.get_all("Classifier") or []:
                        if c.startswith("License ::"):
                            lic = c.split("::")[-1].strip()
                            break
                if version == "?":
                    version = md.get("Version", "?")
            except Exception:
                pass
            out.append((name, version, lic, req.name))
    return out


def components(root):
    root = pathlib.Path(root)
    return sorted(set(_node_lock(root) + _python_requirements(root)))


def write_record(root):
    root = pathlib.Path(root)
    rows = components(root)
    p = root / RECORD
    p.parent.mkdir(parents=True, exist_ok=True)
    body = "\t".join(COLUMNS) + "\n" + "".join("\t".join(r) + "\n" for r in rows)
    if not rows:
        body += "(no third-party components: no dependency manifest or lockfile in the tree)\n"
    p.write_text("# generated by the harness from dependency manifests; do not edit\n" + body,
                 encoding="utf-8", newline="\n")
    return rows


def read_policy(root):
    p = pathlib.Path(root) / POLICY
    if not p.is_file():
        return None
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except ValueError:
        return None
    if not isinstance(data, dict) or not isinstance(data.get("allowed"), list):
        return None
    return {"allowed": [str(x) for x in data["allowed"]], "denied": [str(x) for x in data.get("denied", [])]}


def evaluate(rows, policy):
    """Findings for components outside the policy."""
    findings = []
    allowed = {a.lower() for a in policy["allowed"]}
    denied = {d.lower() for d in policy["denied"]}
    for name, version, lic, source in rows:
        parts = [x.strip().strip("()").lower() for x in re.split(r"\s+(?:or|and)\s+|/", lic)]
        if lic.upper() in ("UNKNOWN", "UNPARSEABLE"):
            findings.append(f"{name}@{version}: license {lic} ({source}) — cannot be shown to satisfy the policy")
        elif any(p in denied for p in parts):
            findings.append(f"{name}@{version}: license {lic} is denied by policy ({source})")
        elif not any(p in allowed for p in parts):
            findings.append(f"{name}@{version}: license {lic} is outside the allowed set ({source})")
    return findings
