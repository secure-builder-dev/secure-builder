"""Record templates rendered from the schemas, so a template header can never
disagree with what the writers emit (spec 02 REQ-3.3.2). The distributable
copies under engine/dist/templates/records are generated by `render_all` and a
self-test asserts they are current."""
from . import schema as sch

HEADER = "© 2026 Casey Houle. All rights reserved."


def _table(schema):
    return f"{sch.marker_line(schema)}\n\n{sch.header_line(schema)}\n{sch.separator_line(schema)}\n"


def gate_log():
    return (f"# Gate log\n\n{HEADER}\n\nOne row per gate run, including every re-run. Append only. A field-mode row\n"
            f"carries mode=field and a field-pass/field-fail verdict; a wrong verdict is superseded by a\n"
            f"later row naming it in `supersedes`, never erased.\n\n{_table(sch.GATE_LOG)}")


def findings_register():
    return (f"# Findings register\n\n{HEADER}\n\nRows are added by a human, or by an agent transcribing an identified human\n"
            f"decision, named in `decided_by`. An automated agent never accepts its own finding.\n\n"
            f"## Table A — Permanent checks\n\nEvery P0/P1 finding, from any source, becomes a row here before its fix commits.\n"
            f"The class is written generally enough to catch the next instance. Read at gate\n"
            f"start: a row whose mechanism is missing or broken is a blocking finding.\n\n{_table(sch.FINDINGS_A)}\n"
            f"## Table B — Accepted risks and compensating controls\n\nA row may be marked accepted only when the proof column is satisfied. Read at\n"
            f"gate start and at every release decision; unsatisfied proof is reported every run.\n"
            f"Ungated inbound code the team knowingly accepts is recorded here too.\n\n{_table(sch.FINDINGS_B)}")


def governance_changelog():
    return (f"# Governance changelog\n\n{HEADER}\n\nOne row per change to the rule set, written before the commit. The sign-off\n"
            f"records what the human was shown. This is the harness's configuration change\n"
            f"control record.\n\n{_table(sch.GOVERNANCE)}")


def carried_findings():
    return (f"# Carried findings — plan of action\n\n{HEADER}\n\nFindings with no available remediation, in the form of a plan-of-action record:\n"
            f"owner, milestone, dates, and an append-only status history. A carried finding\n"
            f"past its review-by date, or whose upstream fix has since become available, blocks.\n\n{_table(sch.CARRIED)}")


def standing_state_deltas():
    return (f"# Standing-state deltas\n\n{HEADER}\n\nThe continuous monitoring record: each measured delta between gate snapshots\n"
            f"and its disposition (a findings-register row explaining why it is expected, or a ticket).\n\n{_table(sch.DELTAS)}")


def reconciliation_obligations():
    return (f"# Reconciliation obligations\n\n{HEADER}\n\nThe debt ledger for field mode: every check deferred in a field run is owed here\n"
            f"until a full re-gate specifically confirms it. Counted and aged at every gate.\n\n{_table(sch.OBLIGATIONS)}")


def high_side_changes():
    return (f"# High-side changes\n\n{HEADER}\n\nChanges originated on the high side of a domain boundary: what, why it could not\n"
            f"wait for the low-side path, who authorized it, and its back-port status.\n\n{_table(sch.DIVERGENCE)}")


def ingest_records():
    return (f"# Ingest records\n\n{HEADER}\n\nChain of custody for every bundle ingested across a boundary: identifier, dates,\n"
            f"hash result, and whether the content was modified in transit.\n\n{_table(sch.INGEST)}")


RENDERERS = {
    "gate-log.md": gate_log,
    "findings-register.md": findings_register,
    "governance-changelog.md": governance_changelog,
    "carried-findings.md": carried_findings,
    "standing-state-deltas.md": standing_state_deltas,
    "reconciliation-obligations.md": reconciliation_obligations,
    "high-side-changes.md": high_side_changes,
    "ingest-records.md": ingest_records,
}


def render_all(directory):
    import pathlib
    d = pathlib.Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    for name, fn in RENDERERS.items():
        (d / name).write_text(fn(), encoding="utf-8", newline="\n")
    return sorted(RENDERERS)
